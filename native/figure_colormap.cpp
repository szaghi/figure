// Three kinds of maps are known by name: the bundled ones (third_party/colormaps/<name>.csv, 256 RGB samples each,
// embedded at build time by native/CMakeLists.txt), ImPlot's own (Viridis, Jet, ...: registered by ImPlot with its
// context) and the user's (loaded from a CSV file or a ParaView JSON preset, kept here for the process's life). A map
// is registered with ImPlot (AddColormap) at its first use, under its name; the reversed map (<name>_r) and the
// discrete one (levels bands, registered as "<name>|<levels>", ImPlot's qualitative kind: no blending between bands)
// are derived from it the same way. ImPlot keeps colormaps for its context's life and cannot replace one: a new
