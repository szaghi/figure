int fig_colormap(const char *name, int name_len, int levels, int *id) {
   try {
      *id = -1;
      const std::string n = str(name, name_len);
      if (!ImPlot::GetCurrentContext()) return fail(FIG_ERR_STATE, "ip_colormap: figure is not initialized");
      if (levels != 0 && (levels < 2 || levels > MAX_LEVELS))
         return fail(FIG_ERR_ARGUMENT, "ip_colormap: levels must be in [2, " + std::to_string(MAX_LEVELS) + "], got " +
                                           std::to_string(levels));
      std::string base;
      bool reversed = false;
      if (!resolves(n, base, reversed))
         return fail(FIG_ERR_ARGUMENT, "ip_colormap: unknown colormap '" + n + "' (ip_colormap_names lists them)");
      const int builtin = implot_map(base);
      const int builtin_id = builtin >= 0 ? ImPlot::GetColormapIndex(IMPLOT_MAPS[builtin]) : -1;
      if (builtin >= 0 && builtin_id < 0) // ImPlot renamed one of its maps: IMPLOT_MAPS is out of date
         return fail(FIG_ERR_FAILED, "ip_colormap: ImPlot has no colormap '" + base + "'");
      if (builtin >= 0 && !reversed && levels == 0) {
         *id = builtin_id;
         return FIG_OK;
      }
      const std::string registered = levels > 0 ? n + "|" + std::to_string(levels) : n;
      *id = ImPlot::GetColormapIndex(registered.c_str());
      if (*id >= 0) return FIG_OK;
      table_t keys;
      bool qual = false;
      if (builtin >= 0) {
         const int b = builtin_id;
         qual = ImPlot::GetCurrentContext()->ColormapData.IsQual(b);
         for (int i = 0; i < ImPlot::GetColormapSize(b); ++i) {
            const ImVec4 c = ImPlot::GetColormapColor(i, b);
            keys.push_back({c.x, c.y, c.z});
         }
      } else {
         const table_t *t = bundled_map(base);
         if (!t) t = user_map(base);
         if (!t) return fail(FIG_ERR_FAILED, "ip_colormap: the table of '" + base + "' cannot be read");
         keys = *t;
      }
      if (reversed) std::reverse(keys.begin(), keys.end());
      if (levels > 0) { // a band each, its colour the map's at the band's centre
         table_t bands(static_cast<size_t>(levels));
         for (int k = 0; k < levels; ++k) {
            const double t = (k + 0.5) / levels;
            bands[static_cast<size_t>(k)] =
               qual ? keys[std::min(static_cast<size_t>(t * keys.size()), keys.size() - 1)] : lerp(keys, t);
         }
         keys = std::move(bands);
         qual = true;
      }
      std::vector<ImVec4> colours;
      for (const auto &k : keys)
         colours.emplace_back(static_cast<float>(k[0]), static_cast<float>(k[1]), static_cast<float>(k[2]), 1.0f);
      *id = ImPlot::AddColormap(registered.c_str(), colours.data(), static_cast<int>(colours.size()), qual);
      return FIG_OK;
   } catch (const std::exception &e) {
      return fail(FIG_ERR_EXCEPTION, std::string("C++ exception: ") + e.what());
   } catch (...) {
      return fail(FIG_ERR_EXCEPTION, "unknown C++ exception");
   }
}

int fig_load_colormap(const char *name, int name_len, const char *path, int path_len) {
   try {
      const std::string n = str(name, name_len), file = str(path, path_len);
      const std::string where = "ip_load_colormap: " + file;
      if (n.empty() || n.find('|') != std::string::npos || n.rfind("FIGURE ", 0) == 0)
         return fail(FIG_ERR_ARGUMENT, "ip_load_colormap: the name '" + n +
                                           "' is not allowed (empty, with '|', or starting with 'FIGURE ')");
      std::string base;
      bool reversed = false;
      if (resolves(n, base, reversed))
         return fail(FIG_ERR_ARGUMENT, "ip_load_colormap: the name '" + n + "' is taken (" +
                                           (reversed ? "the reverse of '" + base + "'" : std::string("a colormap")) +
                                           "): ImPlot cannot replace a colormap");
      std::ifstream in(file, std::ios::binary);
      if (!in) return fail(FIG_ERR_FAILED, where + ": cannot be read");
      std::ostringstream all;
      all << in.rdbuf();
      const std::string text = all.str();
      const size_t first = text.find_first_not_of(" \t\r\n");
      table_t rows;
      std::string err;
      const bool json = first != std::string::npos && (text[first] == '[' || text[first] == '{');
      if (!(json ? parse_paraview(text, where, n, rows, err) : parse_csv(text, where, rows, err)))
         return fail(FIG_ERR_ARGUMENT, err);
      user_maps.push_back({n, std::move(rows)});
      return FIG_OK;
   } catch (const std::exception &e) {
      return fail(FIG_ERR_EXCEPTION, std::string("C++ exception: ") + e.what());
   } catch (...) {
      return fail(FIG_ERR_EXCEPTION, "unknown C++ exception");
   }
}

int fig_colormap_count(void) {
   return static_cast<int>(sizeof(COLORMAPS) / sizeof(COLORMAPS[0])) + IMPLOT_COUNT + static_cast<int>(user_maps.size());
}

int fig_colormap_name(int index, char *buf, int buf_len) {
   const int nb = static_cast<int>(sizeof(COLORMAPS) / sizeof(COLORMAPS[0]));
   std::string n;
   if (index >= 1 && index <= nb) n = COLORMAPS[index - 1].name;
   else if (index > nb && index <= nb + IMPLOT_COUNT) n = IMPLOT_MAPS[index - nb - 1];
   else if (index > nb + IMPLOT_COUNT && index <= fig_colormap_count())
      n = user_maps[static_cast<size_t>(index - nb - IMPLOT_COUNT - 1)].name;
   const int len = static_cast<int>(n.size());
   if (len > 0 && buf_len > 0) std::memcpy(buf, n.data(), static_cast<size_t>(std::min(len, buf_len)));
   return len;
}
