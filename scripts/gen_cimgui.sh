#!/usr/bin/env bash
# Generate cimgui, the C API of Dear ImGui FIGURE binds, against a Dear ImGui commit, into third_party/cimgui/.
#
# cimgui publishes generated sources only at its tags; between tags (a docking head ahead of the last tag) FIGURE runs
# cimgui's own generator. The result is vendored, so building FIGURE needs neither this script nor LuaJIT: run it only
# to move Dear ImGui.
#
# Usage: scripts/gen_cimgui.sh IMGUI_COMMIT [CIMGUI_TAG]
#   IMGUI_COMMIT  a commit of ocornut/imgui (the docking branch's head, for instance)
#   CIMGUI_TAG    the cimgui tag whose generator is run (default 1.93.1WIPdock)
# Needs: git, a C preprocessor (gcc), and LuaJIT (cimgui's generator refuses plain Lua): `luajit` on the PATH, or
# LUAJIT=/path/to/luajit.
#
# Writes third_party/cimgui/: cimgui.cpp, cimgui.h, cimconfig.h, LICENSE (cimgui's); generator/output/*.json (read by
# scripts/gen_bindings.py and scripts/gen_names.py); imgui/: the Dear ImGui files FIGURE compiles, its headers, the
# SDL3 and OpenGL3 backends and its LICENSE.txt; VERSIONS (what was generated, from what).
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
commit="${1:?usage: scripts/gen_cimgui.sh IMGUI_COMMIT [CIMGUI_TAG]}"
tag="${2:-1.93.1WIPdock}"
luajit="${LUAJIT:-luajit}"
command -v "$luajit" > /dev/null || { echo "gen_cimgui.sh: no LuaJIT ($luajit): set LUAJIT" >&2; exit 1; }
work="$(mktemp -d)"
trap 'rm -rf -- "$work"' EXIT

git -c advice.detachedHead=false clone --quiet --depth 1 --branch "$tag" https://github.com/cimgui/cimgui "$work/cimgui"
git clone --quiet https://github.com/ocornut/imgui "$work/imgui"
git -C "$work/imgui" -c advice.detachedHead=false checkout --quiet "$commit"
full="$(git -C "$work/imgui" rev-parse HEAD)"
version="$(sed -n 's/^#define IMGUI_VERSION  *"\(.*\)"/\1/p' "$work/imgui/imgui.h")"
rm -rf -- "$work/cimgui/imgui" && cp -r "$work/imgui" "$work/cimgui/imgui" && rm -rf -- "$work/cimgui/imgui/.git"

# cimgui's generator.sh, with the LuaJIT given (its own call is `luajit`)
(cd "$work/cimgui/generator" && sed "s|^luajit\$suffix |\"$luajit\" |" generator.sh > generator_figure.sh &&
   bash generator_figure.sh > "$work/generator.log" 2>&1) || { tail -30 "$work/generator.log"; exit 1; }

out="$root/third_party/cimgui"
rm -rf -- "$out"
mkdir -p "$out/generator/output" "$out/imgui/backends"
for f in cimgui.cpp cimgui.h cimconfig.h LICENSE; do cp "$work/cimgui/$f" "$out/$f"; done
cp "$work/cimgui/generator/output/"*.json "$out/generator/output/"
for f in imgui.cpp imgui_draw.cpp imgui_widgets.cpp imgui_tables.cpp imgui_demo.cpp imgui.h imgui_internal.h \
         imconfig.h imstb_rectpack.h imstb_textedit.h imstb_truetype.h LICENSE.txt \
         backends/imgui_impl_sdl3.cpp backends/imgui_impl_sdl3.h backends/imgui_impl_opengl3.cpp \
         backends/imgui_impl_opengl3.h backends/imgui_impl_opengl3_loader.h; do
   cp "$work/cimgui/imgui/$f" "$out/imgui/$f"
done
cat > "$out/VERSIONS" <<EOF
Dear ImGui  $version, commit $full (ocornut/imgui)
cimgui      generated by scripts/gen_cimgui.sh with the generator of cimgui's tag $tag
LuaJIT      $("$luajit" -v 2>&1 | head -1)
EOF
echo "gen_cimgui.sh: third_party/cimgui: Dear ImGui $version ($full), cimgui generator $tag"
