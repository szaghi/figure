"""Generate the documentation's tables that restate the code, so that a page cannot drift from it.

Each table is written once, into docs/guide/_generated/, and included by the pages (``<!--@include: ...-->``):

- ``modules.md``: the modules ``use figure`` re-exports and ``figure_testing``, each with the first line of its module
  doc comment (src/lib/<module>.F90);
- ``native.md``: the native layer's third-party parts, from the "Pinned third-party versions" comment of
  native/CMakeLists.txt: what each is, its pin, and whether the first build fetches it (``FetchContent_Declare``) or
  it is vendored in third_party/;
- ``rec-keys.md``: the header lines of a recording (``#! key value``), from scripts/docs_media.py's docstring.

    python3 scripts/gen_doc_tables.py           write the tables
    python3 scripts/gen_doc_tables.py --check   exit 1 if a committed table differs from the generated one

scripts/check_docs.py runs the check by default. Standard library only.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "src" / "lib"
OUT = ROOT / "docs" / "guide" / "_generated"
NOTE = "<!-- generated by scripts/gen_doc_tables.py from {src}: do not edit -->\n"
INTERNAL = {"figure_c_native", "figure_cimgui_enums", "figure_icons"}  # re-exported for constants only


def module_line(module: str) -> str:
    """The first line of a module's doc comment, without its ``<module>, `` lead."""
    text = (LIB / f"{module}.F90").read_text()
    m = re.search(rf"^module {module}\s*\n!<\s*(.*)$", text, re.M | re.I)
    line = m.group(1).strip() if m else ""
    return re.sub(rf"^{module},\s*", "", line)


def modules() -> str:
    """The table of the public modules."""
    text = re.sub(r"&\s*\n\s*", " ", (LIB / "figure.F90").read_text())
    used = sorted(set(re.findall(r"^use\s+(figure_\w+)", text, re.M | re.I)) - INTERNAL)
    rows = [f"| `{m}` | {module_line(m)} |" for m in used]
    rows.append(f"| `figure_testing` | {module_line('figure_testing')} (`use figure_testing`, apart from `figure`) |")
    head = "| Module | What it holds |\n|---|---|\n"
    return NOTE.format(src="src/lib/figure.F90 and the modules' doc comments") + head + "\n".join(rows) + "\n"


def native() -> str:
    """The table of the native layer's third-party parts."""
    text = (ROOT / "native" / "CMakeLists.txt").read_text()
    fetched = {n.lower() for n in re.findall(r"FetchContent_Declare\((\w+)", text)}
    block = text.split("# Pinned third-party versions:\n", 1)[1].split("\ncmake_minimum_required", 1)[0]
    entries: list[list[str]] = []
    for line in block.splitlines():
        body = line[1:].rstrip()  # without '#'
        m = re.match(r"^ {3}(\S.*?)\s*(?:->\s*(.*))?$", body)
        if m and not body.startswith(" " * 4):
            entries.append([m.group(1), m.group(2) or ""])
        elif entries:
            entries[-1][1] += " " + body.strip()
    rows = []
    for head, what in entries:
        name, _, pin = head.partition(" ")
        key = name.lower().replace("sdl", "sdl3") if name.lower() == "sdl" else name.lower()
        vendored = re.search(r"vendored[^,;]*? in (third_party/[\w./-]+)", what)
        if key in fetched:
            how = "fetched by the first build"
        elif vendored:
            how = f"vendored in `{vendored.group(1)}`"
        else:
            how = "vendored"
        what = re.sub(r",?\s*vendored [^;()]*?third_party/[\w./-]+( \([^)]*\))?", "", what).strip(" ,;")
        rows.append(f"| {name} | {pin.strip() or '—'} | {how} | {what or '—'} |")
    head = "| Part | Pin | Source | What it is |\n|---|---|---|---|\n"
    return NOTE.format(src="native/CMakeLists.txt") + head + "\n".join(rows) + "\n"


def rec_keys() -> str:
    """The table of a recording's header lines."""
    doc = (ROOT / "scripts" / "docs_media.py").read_text().split('"""', 2)[1]
    entries: list[list[str]] = []
    col = 0  # the meanings' column, from the first header line (the docstring aligns them)
    for line in doc.splitlines():
        m = re.match(r"^\s+#! (\S+)", line)
        if m:
            if not col:
                col = len(line) - len(re.split(r"\s{2,}", line.strip())[-1])
            entries.append([m.group(1), line[m.end() : col].strip(), line[col:].strip()])
        elif entries and len(line) > col and not line[:col].strip():
            entries[-1][2] += " " + line.strip()
    rows = []
    for key, value, what in entries:
        what = re.sub(r"``([^`]*)``", r"`\1`", what)
        rows.append(f"| `#! {key}` | {f'`{value}`' if value else ''} | {what} |")
    head = "| Header line | Example | Meaning |\n|---|---|---|\n"
    return NOTE.format(src="scripts/docs_media.py's docstring") + head + "\n".join(rows) + "\n"


TABLES = {"modules.md": modules, "native.md": native, "rec-keys.md": rec_keys}


def problems() -> list[str]:
    """Committed tables that differ from the generated ones."""
    return [
        f"docs/guide/_generated/{name} is not current: run python3 scripts/gen_doc_tables.py"
        for name, make in TABLES.items()
        if not (OUT / name).is_file() or (OUT / name).read_text() != make()
    ]


def main(argv: list[str]) -> int:
    """Write the tables, or check them."""
    if argv == ["--check"]:
        bad = problems()
        for b in bad:
            print(f"gen_doc_tables: {b}", file=sys.stderr)
        return 1 if bad else 0
    if argv:
        print("usage: gen_doc_tables.py [--check]", file=sys.stderr)
        return 2
    OUT.mkdir(parents=True, exist_ok=True)
    for name, make in TABLES.items():
        (OUT / name).write_text(make())
        print(OUT.relative_to(ROOT) / name)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
