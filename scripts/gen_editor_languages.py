"""Generate the Fortran code editor's languages from ImGuiColorTextEdit's language files.

The fork's languages (``third_party/ImGuiColorTextEdit/languages/*.h``) are definitions (comments, strings, keyword
sets) and tokenizers, most of them state machines generated by re2c (numbers, JSON's and Markdown's tokens, Lua's long
brackets). This script translates them into the module ``figure_code_languages_fork``
(``src/paths/fortran/editor/figure_code_languages_fork.F90``) for the Fortran path's code editor (szaghi/figure#15
P16): each re2c function into a Fortran function of the same states (its labels, ``GO TO``s and ``SELECT CASE``s, the
code points of the line from index ``s`` to ``e``, past the line's end read as 0), each language's definition into the
data ``fork_language`` hands out. The tokenizers the fork writes by hand (C's identifiers and punctuation, Julia's) are
ported by hand in ``figure_code_language``.

Usage::

    python3 -I scripts/gen_editor_languages.py          # write the module
    python3 -I scripts/gen_editor_languages.py --check  # exit 1 if the committed module differs

Standard library only (Python >= 3.11).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party" / "ImGuiColorTextEdit" / "languages"
OUT = ROOT / "src" / "paths" / "fortran" / "editor" / "figure_code_languages_fork.F90"

# the re2c functions: (file, C++ name, Fortran name, kind: number | token | level)
MACHINES = [
    ("TextEditorC.h", "getNumber", "c_number", "number"),
    ("TextEditorCs.h", "getNumber", "cs_number", "number"),
    ("TextEditorPython.h", "getNumber", "python_number", "number"),
    ("TextEditorLua.h", "getNumber", "lua_number", "number"),
    ("TextEditorLua.h", "commentLevelStart", "lua_comment_start", "level"),
    ("TextEditorLua.h", "commentLevelEnd", "lua_comment_end", "level"),
    ("TextEditorLua.h", "stringLevelStart", "lua_string_start", "level"),
    ("TextEditorLua.h", "stringLevelEnd", "lua_string_end", "level"),
    ("TextEditorJson.h", "tokenize", "json_token", "token"),
    ("TextEditorMarkdown.h", "tokenize", "markdown_token", "token"),
]
LANGUAGES = [
    ("AngelScript", "TextEditorAngelScript.h"), ("C", "TextEditorC.h"), ("C#", "TextEditorCs.h"),
    ("C++", "TextEditorCpp.h"), ("GLSL", "TextEditorGlsl.h"), ("HLSL", "TextEditorHlsl.h"),
    ("JSON", "TextEditorJson.h"), ("Julia", "TextEditorJulia.h"), ("Lua", "TextEditorLua.h"),
    ("Markdown", "TextEditorMarkdown.h"), ("Python", "TextEditorPython.h"), ("SQL", "TextEditorSql.h"),
    ("WGSL", "TextEditorWgsl.h"),
]
COLORS = {"text": 0, "keyword": 1, "declaration": 2, "number": 3, "string": 4, "punctuation": 5, "preprocessor": 6,
          "identifier": 7, "knownIdentifier": 8, "comment": 9}
# the tokenizer codes figure_code_language dispatches on (TOK_* there)
TOKENS = {"TextEditorC::isPunctuation": "TOK_C", "isPunctuation": None, "TextEditorC::getIdentifier": "TOK_C",
          "getIdentifier": None, "TextEditorC::getNumber": "TOK_C", "getNumber": None, "tokenize": None,
          "commentLevelStart": None, "commentLevelEnd": None, "stringLevelStart": None, "stringLevelEnd": None}
WIDTH = 118
# the tokenizers each language uses (its getDefinition's isPunctuation, getIdentifier, getNumber, customTokenizer,
# commentLevelStart, stringLevelStart), as figure_code_language's fork_definition sets them: checked here, so a change
# of the fork's files stops the generation
EXPECTED = {
    "AngelScript": ("C:isPunctuation", "C:getIdentifier", "C:getNumber", "-", "-", "-"),
    "C": ("isPunctuation", "getIdentifier", "getNumber", "-", "-", "-"),
    "C#": ("C:isPunctuation", "C:getIdentifier", "getNumber", "-", "-", "-"),
    "C++": ("C:isPunctuation", "C:getIdentifier", "C:getNumber", "-", "-", "-"),
    "GLSL": ("C:isPunctuation", "C:getIdentifier", "C:getNumber", "-", "-", "-"),
    "HLSL": ("C:isPunctuation", "C:getIdentifier", "C:getNumber", "-", "-", "-"),
    "JSON": ("-", "-", "-", "tokenize", "-", "-"),
    "Julia": ("isPunctuation", "getIdentifier", "getNumber", "tokenize", "-", "-"),
    "Lua": ("C:isPunctuation", "C:getIdentifier", "getNumber", "-", "commentLevelStart", "stringLevelStart"),
    "Markdown": ("-", "-", "-", "tokenize", "-", "-"),
    "Python": ("C:isPunctuation", "C:getIdentifier", "getNumber", "-", "-", "-"),
    "SQL": ("C:isPunctuation", "C:getIdentifier", "C:getNumber", "-", "-", "-"),
    "WGSL": ("C:isPunctuation", "C:getIdentifier", "C:getNumber", "-", "-", "-"),
}


def char_value(tok: str) -> int:
    """A C character or integer literal's value."""
    tok = tok.strip()
    if tok.startswith("'"):
        body = tok[1:-1]
        esc = {"\\'": 39, "\\\\": 92, '\\"': 34, "\\n": 10, "\\t": 9, "\\r": 13, "\\0": 0, "\\v": 11,
               "\\f": 12, "\\a": 7, "\\b": 8}
        if body in esc:
            return esc[body]
        if body.startswith("\\x"):
            return int(body[2:], 16)
        if len(body) != 1:
            raise ValueError(f"character literal {tok!r}")
        return ord(body)
    return int(tok, 0)


def ranges(values: list[int]) -> list[str]:
    """Case values as Fortran case selectors, consecutive ones as ranges."""
    vs = sorted(set(values))
    out = []
    k = 0
    while k < len(vs):
        j = k
        while j + 1 < len(vs) and vs[j + 1] == vs[j] + 1:
            j += 1
        out.append(f"{vs[k]}_int32" if j == k else f"{vs[k]}_int32:{vs[j]}_int32")
        k = j + 1
    return out


def function_body(text: str, name: str) -> str:
    """The re2c block of a C++ static function (between its `{` after `marker;` and the block's end)."""
    m = re.search(r"static [\w:]+ " + re.escape(name) + r"\(", text)
    if m is None:
        raise ValueError(f"function {name} not found")
    start = text.index("\n{", m.end()) + 2
    depth = 1
    k = start
    while depth:
        if text[k] == "{":
            depth += 1
        elif text[k] == "}":
            depth -= 1
        k += 1
    return text[start : k - 1]


class Translator:
    """A re2c block into Fortran statements."""

    def __init__(self, kind: str) -> None:
        self.kind = kind
        self.out: list[str] = []

    def label(self, name: str) -> int:
        return 1000 + int(name[2:])

    def emit(self, depth: int, s: str) -> None:
        self.out.append("   " * (depth + 1) + s)

    def statements(self, lines: list[str], k: int, depth: int, stop_at_close: bool) -> int:
        """Translate statements from line k; return the index after the block."""
        while k < len(lines):
            ln = lines[k].strip()
            if not ln:
                k += 1
                continue
            if ln == "}":
                if stop_at_close:
                    return k + 1
                raise ValueError("unbalanced }")
            if ln in ("ImWchar yych;", "unsigned int yyaccept = 0;"):
                k += 1
                continue
            m = re.fullmatch(r"(yy\d+):", ln)
            if m:
                if depth:
                    raise ValueError("a label inside a block")
                self.out.append(f"{self.label(m.group(1))} continue")
                k += 1
                continue
            if ln == "yych = i < end ? *i : 0;":
                self.emit(depth, "yych = 0_int32")
                self.emit(depth, "if (i < e) yych = cp(i)")
                k += 1
                continue
            if ln == "++i;":
                self.emit(depth, "i = i + 1_int32")
                k += 1
                continue
            if ln == "marker = i;":
                self.emit(depth, "marker = i")
                k += 1
                continue
            if ln == "i = marker;":
                self.emit(depth, "i = marker")
                k += 1
                continue
            m = re.fullmatch(r"yyaccept = (\d+);", ln)
            if m:
                self.emit(depth, f"yyaccept = {m.group(1)}_int32")
                k += 1
                continue
            m = re.fullmatch(r"(?:else )?goto (yy\d+);", ln)
            if m:
                self.emit(depth, f"go to {self.label(m.group(1))}")
                k += 1
                continue
            m = re.fullmatch(r"if \(i >= end\) goto (yy\d+);", ln)
            if m:
                self.emit(depth, f"if (i >= e) go to {self.label(m.group(1))}")
                k += 1
                continue
            m = re.fullmatch(r"if \((yych|yyaccept) (<=|>=|<|>|==) ('.*'|0x[0-9A-Fa-f]+|\d+)\) goto (yy\d+);", ln)
            if m:
                self.emit(depth, f"if ({m.group(1)} {m.group(2)} {char_value(m.group(3))}_int32) go to "
                                 f"{self.label(m.group(4))}")
                k += 1
                continue
            m = re.fullmatch(r"if \(yych (<=|>=|<|>|==) ('.*'|0x[0-9A-Fa-f]+|\d+)\) \{", ln)
            if m:
                self.emit(depth, f"if (yych {m.group(1)} {char_value(m.group(2))}_int32) then")
                k = self.statements(lines, k + 1, depth + 1, True)
                nxt = lines[k].strip() if k < len(lines) else ""
                if nxt == "else {":
                    self.emit(depth, "else")
                    k = self.statements(lines, k + 1, depth + 1, True)
                self.emit(depth, "endif")
                continue
            if ln == "} else {":
                raise ValueError("an else not after an if block")
            m = re.fullmatch(r"switch \((yych|yyaccept)\) \{", ln)
            if m:
                k = self.switch(lines, k + 1, depth, m.group(1))
                continue
            if ln.startswith("{"):
                k = self.action(lines, k, depth)
                continue
            raise ValueError(f"unknown statement {ln!r}")
        return k

    def switch(self, lines: list[str], k: int, depth: int, var: str) -> int:
        self.emit(depth, f"select case ({var})")
        values: list[int] = []
        while True:
            ln = lines[k].strip()
            if ln == "}":
                self.emit(depth, "endselect")
                return k + 1
            m = re.fullmatch(r"case ('(?:\\.|[^'])*'|0x[0-9A-Fa-f]+|\d+):(?: (goto yy\d+;))?", ln)
            if m:
                values.append(char_value(m.group(1)))
                if m.group(2):
                    for ln_ in wrap("case (", ranges(values), "      "):
                        self.emit(depth, ln_)
                    self.out[-1] += ")"
                    target = re.fullmatch(r"goto (yy\d+);", m.group(2)).group(1)
                    self.emit(depth + 1, f"go to {self.label(target)}")
                    values = []
                k += 1
                continue
            m = re.fullmatch(r"default:(?: (goto yy\d+;))?", ln)
            if m:
                self.emit(depth, "case default")
                if m.group(1):
                    target = re.fullmatch(r"goto (yy\d+);", m.group(1)).group(1)
                    self.emit(depth + 1, f"go to {self.label(target)}")
                    k += 1
                else:
                    k += 1
                    while lines[k].strip() != "}":
                        k = self.statements_one(lines, k, depth + 1)
                continue
            raise ValueError(f"unknown case {ln!r}")

    def statements_one(self, lines: list[str], k: int, depth: int) -> int:
        """One statement of a default branch."""
        sub = Translator(self.kind)
        end = sub.statements(lines[k : k + 1], 0, depth, False)
        self.out.extend(sub.out)
        return k + end

    def action(self, lines: list[str], k: int, depth: int) -> int:
        """A `{ ... }` action: a colour or a level set, a return."""
        text = ""
        while True:
            text += lines[k].strip() + " "
            k += 1
            if text.count("{") == text.count("}"):
                break
        body = text.strip()[1:-1].strip()
        for st in [s.strip() for s in body.split(";") if s.strip()]:
            m = re.fullmatch(r"color = TextEditor::Color::(\w+)", st)
            if m:
                self.emit(depth, f"color = {COLORS[m.group(1)]}_int8")
                continue
            m = re.fullmatch(r"level = i - start - (\d+)", st)
            if m:
                self.emit(depth, f"level = i - s - {m.group(1)}_int32")
                continue
            if st == "return start":
                self.emit(depth, "t = s")
                self.emit(depth, "return")
                continue
            if st == "return i":
                self.emit(depth, "t = i")
                self.emit(depth, "return")
                continue
            raise ValueError(f"unknown action {st!r}")
        return k


def machine(file: str, cname: str, fname: str, kind: str) -> list[str]:
    """A re2c function as a Fortran function."""
    text = (SRC / file).read_text(encoding="utf-8")
    body = function_body(text, cname)
    tr = Translator(kind)
    tr.statements(body.split("\n"), 0, 0, False)
    extra = {"number": "", "token": ", color", "level": ", level"}[kind]
    out = [
        f"   function {fname}(cp, s, e{extra}) result(t)",
        f"   !< `{file[:-2]}::{cname}` (re2c's state machine, translated): the end of the token from glyph `s` (`s`: none).",
        "   integer(int32), intent(in)    :: cp(:) !< The line's code points.",
        "   integer(int32), intent(in)    :: s, e  !< Start, end (past the line's last glyph).",
    ]
    if kind == "token":
        out.append("   integer(int8),  intent(inout) :: color !< The token's colour.")
    if kind == "level":
        out.append("   integer(int32), intent(out)   :: level !< The bracket's level.")
    out += [
        "   integer(int32)                :: t     !< End of the token.",
        "   integer(int32)                :: i, marker, yych, yyaccept !< re2c's state.",
        "",
        "   i = s",
        "   marker = s",
        "   yyaccept = 0_int32",
    ]
    if kind == "level":
        out.append("   level = 0_int32")
    out += tr.out
    out.append(f"   endfunction {fname}")
    return out


def string_list(text: str, name: str) -> list[str]:
    """A `static const char* const name[] = { ... };` list's strings."""
    m = re.search(r"static const char\* const " + name + r"\[\] = \{(.*?)\};", text, re.S)
    if m is None:
        return []
    return re.findall(r'"((?:\\.|[^"\\])*)"', m.group(1))


def definition(name: str, file: str) -> dict:
    """A language's definition from its getDefinition."""
    text = (SRC / file).read_text(encoding="utf-8")
    m = re.search(r"getDefinition\(\) \{(.*?)return &language;", text, re.S)
    body = m.group(1)
    d: dict = {"name": name}
    for field, value in re.findall(r"language\.(\w+) = ([^;]+);", body):
        d[field] = value.strip()
    d["keywords"], d["declarations"], d["identifiers"] = [], [], []
    for array, target, expr in re.findall(r"for \(auto& \w+ : (\w+)\) \{ language\.(\w+)\.insert\((.*?)\); \}", body):
        prefix = ""
        m2 = re.fullmatch(r'std::string\("((?:\\.|[^"\\])*)"\) \+ \w+', expr.strip())
        if m2:
            prefix = m2.group(1)
        elif not re.fullmatch(r"\w+", expr.strip()):
            raise ValueError(f"{file}: an insertion {expr!r}")
        if target not in d:
            raise ValueError(f"{file}: a set {target!r}")
        d[target] += [prefix + w for w in string_list(body, array)]
    return d


def cstring(v: str) -> str:
    """A C string literal's text (its escapes \\" and \\\\ resolved)."""
    v = v.strip()
    if not (v.startswith('"') and v.endswith('"')):
        raise ValueError(f"string {v!r}")
    return re.sub(r"\\(.)", r"\1", v[1:-1])


def fstring(s: str) -> str:
    """A Fortran character expression of s, its UTF-8 bytes (ASCII printable kept, the others by achar)."""
    if not s:
        return "''"
    parts = []
    run = ""
    for b in s.encode("utf-8"):
        if 32 <= b < 127 and b != 39:
            run += chr(b)
        else:
            if run:
                parts.append(f"'{run}'")
                run = ""
            parts.append(f"achar({b})" if b < 128 else f"char({b})")
    if run:
        parts.append(f"'{run}'")
    return "//".join(parts)


def wrap(prefix: str, items: list[str], indent: str) -> list[str]:
    """`prefix` and comma-separated items, continued at WIDTH columns."""
    lines = []
    line = prefix
    for k, it in enumerate(items):
        piece = it + (", " if k < len(items) - 1 else "")
        if len(line) + len(piece) > WIDTH - 2:
            lines.append(line.rstrip() + " &")
            line = indent
        line += piece
    lines.append(line)
    return lines


def punctuation(name: str, file: str, what: str) -> list[str]:
    """A `punctuation[128]` table as a logical named constant, from 0."""
    text = (SRC / file).read_text(encoding="utf-8")
    m = re.search(r"static const bool punctuation\[128\] = \{(.*?)\};", text, re.S)
    values = re.findall(r"true|false", m.group(1))
    if len(values) != 128:
        raise ValueError(f"{file}: a punctuation table of {len(values)} entries")
    items = [".true." if v == "true" else ".false." for v in values]
    lines = wrap(f"logical, parameter :: {name}(0:127) = [", items, "   ")
    lines[-1] += "]"
    return [f"!< {what}.", *lines, ""]


def generate() -> str:
    """The module's text."""
    out = [
        "!< figure_code_languages_fork, ImGuiColorTextEdit's languages: definitions and re2c tokenizers (generated: do not edit).",
        "module figure_code_languages_fork",
        "!< figure_code_languages_fork, ImGuiColorTextEdit's languages: definitions and re2c tokenizers (generated: do not edit).",
        "!<",
        "!< Written by scripts/gen_editor_languages.py from third_party/ImGuiColorTextEdit/languages/ (szaghi/figure#15",
        "!< P16): the re2c state machines as Fortran functions of the same states (a code point past the line's end is 0, as",
        "!< re2c's `i < end ? *i : 0`), and `fork_data`, each language's comments, strings, flags and keyword sets as",
        "!< figure_code_language reads them.",
        "use, intrinsic :: iso_fortran_env, only : int8, int32",
        "",
        "implicit none",
        "private",
        *wrap("public :: ", [m[2] for m in MACHINES], "          "),
        "public :: fork_data, C_PUNCTUATION, JULIA_PUNCTUATION",
        "",
        *punctuation("C_PUNCTUATION", "TextEditorC.h", "the C languages' ASCII punctuation (TextEditorC::isPunctuation)"),
        *punctuation("JULIA_PUNCTUATION", "TextEditorJulia.h", "Julia's ASCII punctuation (TextEditorJulia::isPunctuation)"),
        "",
        "contains",
    ]
    for m in MACHINES:
        out += machine(*m)
        out.append("")
    out += [
        "   subroutine fork_data(name, field, value, words)",
        "   !< A language's definition: `field` 1 singleLineComment, 2 singleLineCommentAlt, 3 commentStart, 4 commentEnd,",
        "   !< 5 otherStringStart, 6 otherStringEnd, 7 otherStringAltStart, 8 otherStringAltEnd, 9 the flags (preprocess,",
        "   !< escape, single and double quotes, case, nested comments, indentation blocks as digits `p e s d c n i`, the",
        "   !< characters' codes for p and e, 0 none), 10 keywords, 11 declarations, 12 identifiers, 13 the tokenizers (punctuation,",
        "   !< identifier, number, custom, comment levels, string levels as `TOK_*` names); `words` for 10 to 12, LF-separated.",
        "   character(len=*),              intent(in)  :: name  !< The language (as registered).",
        "   integer(int32),                intent(in)  :: field !< Which.",
        "   character(len=:), allocatable, intent(out) :: value !< Its text.",
        "   logical,                       intent(out) :: words !< A list of words.",
        "",
        "   value = ''",
        "   words = field >= 10_int32 .and. field <= 12_int32",
        "   select case (name)",
    ]
    for lname, file in LANGUAGES:
        d = definition(lname, file)
        out.append(f"   case ({fstring(lname)})")
        out.append("      select case (field)")
        for k, key in enumerate(["singleLineComment", "singleLineCommentAlt", "commentStart", "commentEnd",
                                 "otherStringStart", "otherStringEnd", "otherStringAltStart", "otherStringAltEnd"],
                                start=1):
            if key in d:
                out.append(f"      case ({k}_int32)")
                out.append(f"         value = {fstring(cstring(d[key]))}")
        pre = char_value(d["preprocess"]) if "preprocess" in d else 0
        esc = char_value(d["stringEscape"]) if "stringEscape" in d else 0
        flags = [str(pre), str(esc), "1" if d.get("hasSingleQuotedStrings") == "true" else "0",
                 "1" if d.get("hasDoubleQuotedStrings") == "true" else "0",
                 "0" if d.get("caseSensitive") == "false" else "1",
                 "1" if d.get("nestedComments") == "true" else "0",
                 "1" if d.get("indentationForBlocks") == "true" else "0"]
        out.append("      case (9_int32)")
        out.append(f"         value = '{' '.join(flags)}'")
        for k, key in ((10, "keywords"), (11, "declarations"), (12, "identifiers")):
            if d[key]:
                out.append(f"      case ({k}_int32)")
                items = [fstring(w) + "//achar(10)" for w in d[key][:-1]] + [fstring(d[key][-1])]
                lines = wrap("         value = ", items, "                 ")
                lines = [ln.replace(", ", "//") if False else ln for ln in lines]
                out += [ln.replace("//achar(10), ", "//achar(10)// ") for ln in lines]
        toks = []
        for key in ("isPunctuation", "getIdentifier", "getNumber", "customTokenizer", "commentLevelStart",
                    "stringLevelStart"):
            v = d.get(key, "")
            toks.append(v.replace("TextEditorC::", "C:") if v else "-")
        if tuple(toks) != EXPECTED[lname]:
            raise ValueError(f"{file}: the tokenizers changed: {toks}")
        out.append("      case (13_int32)")
        out.append(f"         value = '{' '.join(toks)}'")
        out.append("      endselect")
    out += [
        "   endselect",
        "   endsubroutine fork_data",
        "endmodule figure_code_languages_fork",
    ]
    return "\n".join(out) + "\n"


def main() -> int:
    """Write or check the module."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed module differs")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"gen_editor_languages: {OUT.relative_to(ROOT)} is not current: run python3 scripts/gen_editor_languages.py",
                  file=sys.stderr)
            return 1
        print("gen_editor_languages: the languages are current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"gen_editor_languages: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
