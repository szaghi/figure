"""Generate FIGURE's named icons, ``ICON_*`` UTF-8 strings, from the code point map of the bundled Lucide font.

Input: ``third_party/fonts/lucide-info.json``, the map shipped with the font in the npm package ``lucide-static``
(``font/info.json``, unmodified): every icon by name, with its code point in the Private Use Area. Lucide's older names
of renamed icons are in it too (``alert-circle`` and ``circle-alert``, one glyph), so both get a constant; the
deprecated brand icons are not, so they get none. Outputs, committed to the repository:

  - ``src/lib/figure_icons.F90``: one ``character(len=*), parameter`` per icon, ``ICON_<NAME>`` with the Lucide name
    upper-cased and ``-`` turned into ``_`` (``file-pen`` -> ``ICON_FILE_PEN``), holding the UTF-8 bytes of its code
    point, so that ``ig_button(ICON_PLAY//' Run')`` draws the icon before the text;
  - ``src/lib/figure_icons_public.inc``: the ``public`` statements of those names, included by ``src/lib/figure.F90``
    so that ``use figure`` exports them.

The font itself (``third_party/fonts/lucide.ttf``) is embedded by the native build and merged into every text font.

Usage::

    python3 scripts/gen_icons.py          # regenerate the outputs
    python3 scripts/gen_icons.py --check  # exit 1 if a committed output differs from what would be generated

Standard library only (Python >= 3.11).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAP = ROOT / "third_party" / "fonts" / "lucide-info.json"
MODULE = ROOT / "src" / "lib" / "figure_icons.F90"
PUBLIC = ROOT / "src" / "lib" / "figure_icons_public.inc"
LUCIDE_VERSION = "1.61.0"  # the lucide-static package the font and its map come from (THIRD_PARTY.md)
MAX_LINE = 132
NAME_RE = re.compile(r"[a-z0-9]+(-[a-z0-9]+)*")


def utf8_bytes(code: int) -> list[int]:
    """Return the UTF-8 encoding of a code point as byte values."""
    return list(chr(code).encode("utf-8"))


def icons(path: Path) -> list[tuple[str, str, int]]:
    """Return the icons of the map, sorted by Fortran name.

    Parameters
    ----------
    path : Path
        The code point map (``lucide-info.json``).

    Returns
    -------
    list[tuple[str, str, int]]
        ``(Fortran name, Lucide name, code point)`` per icon.

    Raises
    ------
    ValueError
        If a name is not a Lucide name, a code point is outside the Basic Multilingual Plane's Private Use Area, or two
        names collide.
    """
    data = json.loads(path.read_text(encoding="utf-8"))
    out: list[tuple[str, str, int]] = []
    seen: set[str] = set()
    for name, info in data.items():
        if not NAME_RE.fullmatch(name):
            raise ValueError(f"{path.name}: unexpected icon name {name!r}")
        code = int(info["encodedCode"].lstrip("\\"), 16)
        if not 0xE000 <= code <= 0xF8FF:
            raise ValueError(f"{path.name}: {name} has the code point U+{code:04X}, outside the Private Use Area")
        fortran = "ICON_" + name.upper().replace("-", "_")
        if fortran in seen:
            raise ValueError(f"{path.name}: two icons named {fortran}")
        seen.add(fortran)
        out.append((fortran, name, code))
    return sorted(out)


def module_text(items: list[tuple[str, str, int]]) -> str:
    """Return the Fortran module of the icon constants."""
    width = max(len(f) for f, _, _ in items)
    head = (
        "!< figure_icons, the Lucide icons by name, as UTF-8 strings (generated by scripts/gen_icons.py: do not edit).\n"
        "module figure_icons\n"
        "!< figure_icons, the Lucide icons by name, as UTF-8 strings (generated by scripts/gen_icons.py: do not edit).\n"
        "!<\n"
        f"!< The {len(items)} icons of Lucide {LUCIDE_VERSION} (ISC licence, third_party/fonts), whose font is merged into\n"
        "!< every text font FIGURE loads: an icon goes in any label, at any size, e.g. `ig_button(ICON_PLAY//' Run')`.\n"
        "!< Names are the Lucide names upper-cased, `-` turned into `_`, after `ICON_` (https://lucide.dev/icons/).\n"
        "\n"
        "implicit none\n"
        "private\n"
    )
    body = [*public_lines([f for f, _, _ in items]), ""]
    for f, _, code in items:
        value = "//".join(f"char({b})" for b in utf8_bytes(code))
        body.append(f"character(len=*), parameter :: {f:<{width}} = {value} !< U+{code:04X}.")
    for line in body:
        if len(line) > MAX_LINE:
            raise ValueError(f"line over {MAX_LINE} characters: {line}")
    return head + "\n".join(body) + "\nendmodule figure_icons\n"


def public_lines(names: list[str]) -> list[str]:
    """Return ``public`` statements of ``names``, as many per line as fit in ``MAX_LINE`` columns."""
    lines: list[str] = []
    cur: list[str] = []
    for name in names:
        if cur and len("public :: " + ", ".join([*cur, name])) > MAX_LINE:
            lines.append("public :: " + ", ".join(cur))
            cur = []
        cur.append(name)
    if cur:
        lines.append("public :: " + ", ".join(cur))
    return lines


def public_text(items: list[tuple[str, str, int]]) -> str:
    """Return the ``public`` statements that ``figure.F90`` includes to export the icons."""
    head = "! figure_icons_public.inc: the icons exported by figure.F90 (generated by scripts/gen_icons.py: do not edit)."
    return "\n".join([head, *public_lines([f for f, _, _ in items])]) + "\n"


def main(argv: list[str]) -> int:
    """Generate, or check the committed outputs against the map.

    Parameters
    ----------
    argv : list[str]
        Arguments, without the script name.

    Returns
    -------
    int
        0 on success; 1 if ``--check`` finds a difference or the map is not as expected.
    """
    parser = argparse.ArgumentParser(description="Generate FIGURE's named icons (ICON_*) from the Lucide map.")
    parser.add_argument("--check", action="store_true", help="only check that the committed outputs are current")
    args = parser.parse_args(argv)
    try:
        items = icons(MAP)
        outputs = {MODULE: module_text(items), PUBLIC: public_text(items)}
    except (OSError, ValueError, KeyError) as err:
        print(f"gen_icons: {err}", file=sys.stderr)
        return 1
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"gen_icons: {p.relative_to(ROOT)} is not current: run python3 scripts/gen_icons.py", file=sys.stderr)
        return 1 if stale else 0
    for p, text in outputs.items():
        p.write_text(text, encoding="utf-8")
    print(f"gen_icons: {len(items)} icons, wrote {', '.join(str(p.relative_to(ROOT)) for p in outputs)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
