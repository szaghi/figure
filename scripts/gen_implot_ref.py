"""Write the reference modules of the Fortran path's side-by-side plot tests from the current path's plot modules.

The tests of src/tests/fortran/figure_test_plot_frame*.F90 draw each plot with ImPlot (ImPlot3D) and with the Fortran
plot frame (3-D frame) in one program and compare the two (szaghi/figure#15 P10-P13). Since the seams' switch the
Fortran path's ``figure_implot`` and ``figure_implot3d`` are the frames themselves, so their ImPlot side calls
``figure_implot_ref`` and ``figure_implot3d_ref``: the current path's modules (src/paths/imgui/plot/figure_implot.F90,
src/paths/imgui/plot3d/figure_implot3d.F90) under other names, built by the -fortran modes only (src/tests/fortran/),
over ImPlot and ImPlot3D as on the current path.

Usage: python3 scripts/gen_implot_ref.py           write src/tests/fortran/figure_implot_ref.F90, figure_implot3d_ref.F90
       python3 scripts/gen_implot_ref.py --check   exit status 1 when one is not the current path's module renamed
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODULES = {"figure_implot": ("plot", "ImPlot"), "figure_implot3d": ("plot3d", "ImPlot3D")}
TARGETS = {m: ROOT / "src" / "tests" / "fortran" / f"{m}_ref.F90" for m in MODULES}
TARGET = TARGETS["figure_implot"]  # (check_sync's first)


def source(module: str) -> Path:
    """The current path's source of a module."""
    return ROOT / "src" / "paths" / "imgui" / MODULES[module][0] / f"{module}.F90"


def generate(module: str = "figure_implot") -> str:
    """A reference module's text.

    Parameters
    ----------
    module : str
        figure_implot or figure_implot3d.

    Returns
    -------
    str
        The current path's module, renamed ``<module>_ref``.
    """
    lib = MODULES[module][1]
    head = (
        f"!< {module}_ref, the current path's {module} ({lib}) under another name: the side-by-side tests' {lib}.\n"
        f"!< Generated by scripts/gen_implot_ref.py from src/paths/imgui/{MODULES[module][0]}/{module}.F90: do not edit.\n"
    )
    out = [head.rstrip("\n")]
    for line in source(module).read_text(encoding="utf-8").split("\n"):
        if line == f"module {module}":
            line = f"module {module}_ref"
        elif line == f"endmodule {module}":
            line = f"endmodule {module}_ref"
        out.append(line)
    return "\n".join(out)


def main() -> int:
    """Write or check the reference module.

    Returns
    -------
    int
        Exit status.
    """
    stale = []
    for module, target in TARGETS.items():
        text = generate(module)
        if "--check" in sys.argv[1:]:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                stale.append(target)
            continue
        target.write_text(text, encoding="utf-8")
        print(f"gen_implot_ref: wrote {target.relative_to(ROOT)}")
    for target in stale:
        print(f"gen_implot_ref: {target.relative_to(ROOT)} is not current: run python3 scripts/gen_implot_ref.py",
              file=sys.stderr)
    if "--check" in sys.argv[1:] and not stale:
        print("gen_implot_ref: the reference modules are current")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
