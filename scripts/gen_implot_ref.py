"""Write the reference module of the Fortran path's side-by-side plot tests from the current path's figure_implot.

The tests of src/tests/fortran/figure_test_plot_frame*.F90 draw each plot with ImPlot and with the Fortran plot frame
in one program and compare the two (szaghi/figure#15 P10-P12). Since the seam's switch the Fortran path's
``figure_implot`` is the frame itself, so their ImPlot side calls ``figure_implot_ref``: the current path's module
(src/paths/imgui/plot/figure_implot.F90) under another name, built by the -fortran modes only (src/tests/fortran/),
over ImPlot as on the current path.

Usage: python3 scripts/gen_implot_ref.py           write src/tests/fortran/figure_implot_ref.F90
       python3 scripts/gen_implot_ref.py --check   exit status 1 when it is not the current path's module renamed
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "paths" / "imgui" / "plot" / "figure_implot.F90"
TARGET = ROOT / "src" / "tests" / "fortran" / "figure_implot_ref.F90"
HEAD = (
    "!< figure_implot_ref, the current path's figure_implot (ImPlot) under another name: the side-by-side tests' ImPlot.\n"
    "!< Generated by scripts/gen_implot_ref.py from src/paths/imgui/plot/figure_implot.F90: do not edit.\n"
)


def generate() -> str:
    """The reference module's text.

    Returns
    -------
    str
        The current path's figure_implot, its module renamed figure_implot_ref.
    """
    text = SOURCE.read_text(encoding="utf-8")
    lines = text.split("\n")
    out = [HEAD.rstrip("\n")]
    for line in lines:
        if line == "module figure_implot":
            line = "module figure_implot_ref"
        elif line == "endmodule figure_implot":
            line = "endmodule figure_implot_ref"
        out.append(line)
    return "\n".join(out)


def main() -> int:
    """Write or check the reference module.

    Returns
    -------
    int
        Exit status.
    """
    text = generate()
    if "--check" in sys.argv[1:]:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != text:
            print(f"gen_implot_ref: {TARGET.relative_to(ROOT)} is not current: run python3 scripts/gen_implot_ref.py",
                  file=sys.stderr)
            return 1
        print("gen_implot_ref: the reference module is current")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"gen_implot_ref: wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
