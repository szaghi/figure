"""Generate the Fortran plot frame's table of FIGURE's bundled colormaps from ``third_party/colormaps/<name>.csv``.

The Fortran path's plot frame (``src/paths/fortran/plot/``, szaghi/figure#15 P10 step 7) registers the bundled maps
without the native layer: this script writes their 256 RGB samples, as the CSV files give them (decimal text, read by
the compiler as ``real(real64)`` literals: correctly rounded, as the native layer's ``strtod``), into the module
``figure_plot_colormaps_bundled`` (``src/paths/fortran/plot/figure_plot_colormaps_bundled.F90``). The maps are listed
in the order of their file names (as the native build's ``file(GLOB)``).

Usage::

    python3 -I scripts/gen_plot_colormaps.py          # write the module
    python3 -I scripts/gen_plot_colormaps.py --check  # exit 1 if the committed module differs

Standard library only (Python >= 3.11).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "third_party" / "colormaps"
OUT = ROOT / "src" / "paths" / "fortran" / "plot" / "figure_plot_colormaps_bundled.F90"
SAMPLES = 256
WIDTH = 120


def read_map(path: Path) -> list[tuple[str, str, str]]:
    """The rows of a bundled map: three decimal strings each (``#`` lines skipped)."""
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        text = line.strip()
        if not text or text.startswith("#"):
            continue
        parts = [p.strip() for p in text.split(",")]
        if len(parts) != 3:
            raise ValueError(f"{path.name}: a row of three numbers expected, got {text!r}")
        for p in parts:
            float(p)  # a number, or ValueError
        rows.append((parts[0], parts[1], parts[2]))
    if len(rows) != SAMPLES:
        raise ValueError(f"{path.name}: {SAMPLES} rows expected, got {len(rows)}")
    return rows


def literal(text: str) -> str:
    """A decimal as a ``real(real64)`` literal of the module's kind ``R``."""
    t = text.lower()
    if "e" not in t and "." not in t:
        t += ".0"
    elif t.startswith("."):
        t = "0" + t
    return f"{t}_R"


def wrap(items: list[str], indent: str, first: str, last: str) -> list[str]:
    """Items joined by commas into continued lines of at most WIDTH columns."""
    lines, cur = [], first
    for i, item in enumerate(items):
        piece = item + (", " if i < len(items) - 1 else "")
        if len(cur) + len(piece.rstrip()) + 2 > WIDTH:
            lines.append(cur.rstrip() + " &")
            cur = indent
        cur += piece
    lines.append(cur.rstrip() + last)
    return lines


def generate() -> str:
    """The module's text."""
    files = sorted(SRC.glob("*.csv"))
    names = [f.stem for f in files]
    width = max(len(n) for n in names)
    out = [
        "!< figure_plot_colormaps_bundled, FIGURE's bundled colormaps as tables (generated: do not edit).",
        "module figure_plot_colormaps_bundled",
        "!< figure_plot_colormaps_bundled, FIGURE's bundled colormaps as tables (generated: do not edit).",
        "!<",
        "!< Generated by scripts/gen_plot_colormaps.py from the tables `third_party/colormaps/<name>.csv` (written by",
        "!< scripts/gen_colormaps.py, where their sources and licences are): do not edit. Each map is 256 RGB samples in",
        "!< [0, 1], the CSV's decimals as `real(real64)` literals; `bundled_map(i)` returns the i-th, `BUNDLED_NAMES(i)` its",
        "!< name (the native layer's order).",
        "use, intrinsic :: iso_fortran_env, only : int32, real64",
        "",
        "implicit none",
        "private",
        "public :: BUNDLED_COUNT, BUNDLED_SAMPLES, BUNDLED_NAMES, bundled_map",
        "",
        "integer,        parameter :: R = real64 !< The tables' kind.",
        f"integer(int32), parameter :: BUNDLED_COUNT = {len(names)}_int32 !< Maps.",
        f"integer(int32), parameter :: BUNDLED_SAMPLES = {SAMPLES}_int32 !< Samples of a map.",
    ]
    quoted = [f"'{n.ljust(width)}'" for n in names]
    out += wrap(quoted, "                                                    ",
                f"character(len={width}), parameter :: BUNDLED_NAMES({len(names)}) = [", "] !< Names.")
    for name, f in zip(names, files):
        rows = read_map(f)
        values = [literal(v) for row in rows for v in row]
        ident = "MAP_" + "".join(c if c.isalnum() else "_" for c in name).upper()
        out.append(f"real(real64), parameter :: {ident}(3, {SAMPLES}) = reshape([ &")
        out += wrap(values, "   ", "   ", f"], [3, {SAMPLES}]) !< {name}.")
    out += ["", "contains", "   pure function bundled_map(i) result(rgb)",
            "   !< The i-th bundled map's samples (RGB in [0, 1], one column each); zeros for an i out of range.",
            "   integer(int32), intent(in) :: i                   !< Map (1 .. BUNDLED_COUNT).",
            "   real(real64)               :: rgb(3, BUNDLED_SAMPLES) !< Samples.", "",
            "   select case (i)"]
    for k, name in enumerate(names, start=1):
        ident = "MAP_" + "".join(c if c.isalnum() else "_" for c in name).upper()
        out += [f"   case ({k}_int32)", f"      rgb = {ident}"]
    out += ["   case default", "      rgb = 0.0_R", "   endselect", "   endfunction bundled_map",
            "endmodule figure_plot_colormaps_bundled", ""]
    for line in out:
        if len(line) > WIDTH:
            raise ValueError(f"generated line longer than {WIDTH} columns: {line[:60]}...")
    return "\n".join(out)


def main() -> int:
    """Write the module, or check it."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the committed module differs")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"gen_plot_colormaps: {OUT.relative_to(ROOT)} differs from the tables: run scripts/gen_plot_colormaps.py")
            return 1
        print(f"gen_plot_colormaps: {OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"gen_plot_colormaps: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
