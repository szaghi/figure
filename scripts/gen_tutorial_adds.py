"""Write, in each studio chapter of the tutorial (8 to 26), what its program adds to the previous chapter's, and how
to run it.

Chapter N's program, docs/examples/src/tutNN_<name>.F90, is chapter N-1's with additions. Two regions of each page
docs/manual/tutorial/NN-*.md are generated from the two programs:

- after the link to the whole program, "What this chapter adds": the procedures it defines that the previous program
  does not (each with the first sentence of its ``!<`` doc comment), and those of both whose body changed;
- before the **Next** link, the run line: the program built as chapter 7 says, then run with the options it takes
  (``--examples DIR`` from chapter 10, ``--case DIR`` from chapter 11).

    python3 scripts/gen_tutorial_adds.py           write the regions
    python3 scripts/gen_tutorial_adds.py --check   exit 1 if a page's regions differ from the generated ones

scripts/check_docs.py runs the check by default. Standard library only.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "examples" / "src"
PAGES = ROOT / "docs" / "manual" / "tutorial"
FIRST, LAST = 8, 26  # the studio's chapters
ADDS = ("<!-- adds: generated by scripts/gen_tutorial_adds.py, do not edit -->", "<!-- adds: end -->")
RUN = ("<!-- run: generated by scripts/gen_tutorial_adds.py, do not edit -->", "<!-- run: end -->")
PROC = re.compile(r"^\s*(?:(?:recursive|pure|elemental|impure|module)\s+)*(subroutine|function)\s+(\w+)", re.I)


def program(n: int) -> Path:
    """Chapter n's program (not a solver)."""
    found = [p for p in sorted(SRC.glob(f"tut{n:02d}_*.F90")) if not p.stem.endswith("_heat")]
    if len(found) != 1:
        msg = f"chapter {n}: {len(found)} programs tut{n:02d}_*.F90 (one expected)"
        raise SystemExit(msg)
    return found[0]


def procedures(path: Path) -> dict[str, tuple[str, str]]:
    """Each procedure of a program file: its body (comments and blanks out, for comparison) and its doc line."""
    lines = path.read_text().splitlines()
    out: dict[str, tuple[str, str]] = {}
    k = 0
    while k < len(lines):
        m = PROC.match(lines[k])
        if not m or lines[k].lstrip().lower().startswith("end"):
            k += 1
            continue
        name = m.group(2).lower()
        end = re.compile(rf"^\s*end\s*{m.group(1)}\s+{name}\b", re.I)
        j = k + 1
        while j < len(lines) and not end.match(lines[j]):
            j += 1
        doc = ""
        if k + 1 < len(lines) and lines[k + 1].strip().startswith("!<"):
            doc = lines[k + 1].strip()[2:].strip()
            t = k + 2
            while not re.search(r"[.:]$|[.:] ", doc) and t < j and lines[t].strip().startswith("!<"):
                doc += " " + lines[t].strip()[2:].strip()
                t += 1
            doc = re.split(r"(?<=[.:])\s", doc, maxsplit=1)[0].rstrip(".:")
        body = "\n".join(re.sub(r"!.*$", "", ln).strip() for ln in lines[k + 1 : j])
        body = re.sub(r"tut\d\d_\w+", "tutNN", body)  # a program's own name changes with every chapter
        out[name] = ("\n".join(b for b in body.splitlines() if b), doc)
        k = j + 1
    return out


def adds(n: int) -> str:
    """The "What this chapter adds" region of chapter n."""
    cur, prev = program(n), program(n - 1) if n > FIRST else None
    now = procedures(cur)
    before = procedures(prev) if prev else {}
    new = [p for p in now if p not in before]
    changed = sorted(p for p in now if p in before and now[p][0] != before[p][0])
    lines = [ADDS[0], ""]  # a blank line after each mark: an HTML comment opens a block up to the next one
    if prev is None:
        lines.append(f"**What this chapter adds:** the studio's first program, `{cur.name}`, its procedures:")
    else:
        page = next(PAGES.glob(f"{n - 1:02d}-*.md")).stem
        lines.append(f"**What this chapter adds** to [chapter {n - 1}'s program](./{page}), `{prev.name}`:")
    lines.append("")
    lines += [f"- `{p}`: {now[p][1]}" if now[p][1] else f"- `{p}`" for p in new]
    if changed:
        lines.append("- changed: " + ", ".join(f"`{p}`" for p in changed))
    if not new and not changed:
        lines.append("- no procedure: the changes are in the main program")
    lines += ["", ADDS[1]]
    return "\n".join(lines)


def run_line(n: int) -> str:
    """The run region of chapter n."""
    exe = "./" + program(n).stem
    opts = ""
    if n >= 11:
        opts = " --examples /tmp/studio --case /tmp/studio/plate"
    elif n >= 10:
        opts = " --examples /tmp/studio"
    solver = " (with `tut12_heat` beside it)" if 12 <= n < 22 else " (with `tut22_heat` beside it)" if n >= 22 else ""
    return "\n".join(
        [
            RUN[0],
            "",
            f"**Run it:** build it as [chapter 7](./07-building) shows{solver}, then `{exe}{opts}`.",
            "",
            RUN[1],
        ]
    )


def place(text: str, region: str, marks: tuple[str, str], anchor: re.Pattern[str], after: bool) -> str:
    """Replace the region between `marks` in `text`, or put it after (or before) the first line matching `anchor`."""
    if marks[0] in text:
        i, j = text.index(marks[0]), text.index(marks[1]) + len(marks[1])
        return text[:i] + region + text[j:]
    m = anchor.search(text)
    if not m:
        msg = f"no place for the region {marks[0]!r}"
        raise SystemExit(msg)
    if after and not m.group(0).rstrip().endswith(":"):  # a paragraph ending in ':' leads into what follows it
        return text[: m.end()] + "\n\n" + region + text[m.end() :]
    return text[: m.start()] + region + "\n\n" + text[m.start() :]


def generated() -> dict[Path, str]:
    """Every studio chapter's page with its regions written."""
    out = {}
    for n in range(FIRST, LAST + 1):
        page = next(PAGES.glob(f"{n:02d}-*.md"))
        text = page.read_text()
        text = place(text, adds(n), ADDS, re.compile(r"^The whole programs?: .*(?:\n(?!\n).*)*", re.M), after=True)
        text = place(
            text, run_line(n), RUN, re.compile(r"^\*\*Next:\*\*|^\[Chapter \d+\]|^This is the end", re.M), after=False
        )
        out[page] = text
    return out


def main(argv: list[str]) -> int:
    """Write the regions, or check them."""
    pages = generated()
    if argv == ["--check"]:
        bad = [p for p, t in pages.items() if p.read_text() != t]
        for p in bad:
            print(
                f"gen_tutorial_adds: {p.relative_to(ROOT)} is not current: run python3 scripts/gen_tutorial_adds.py",
                file=sys.stderr,
            )
        return 1 if bad else 0
    if argv:
        print("usage: gen_tutorial_adds.py [--check]", file=sys.stderr)
        return 2
    for p, t in pages.items():
        if p.read_text() != t:
            p.write_text(t)
            print(p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
